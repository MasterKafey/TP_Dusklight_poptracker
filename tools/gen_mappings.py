"""Generate scripts/item_mapping.lua and scripts/location_mapping.lua from the Dusklight apworld.

Usage:
    python tools/gen_mappings.py path/to/tp_dusklight.apworld

The AP ids are computed exactly like the apworld does (tp_dusklight/data.py):
  item id     = 0x54500000 + game item id (items.yaml)
  location id = 0x55000000 + (crc32(location name) & 0xFFFFFF)

Which tracker object each item / location drives comes from tools/data/item_codes.json and
tools/data/location_paths.json, keyed by the apworld's names, so regenerating after an apworld
update only needs this script to be rerun. Names that exist in the apworld but are not mapped
are reported so they can be added.
"""
from __future__ import annotations

import io
import json
import sys
import zipfile
import zlib
from pathlib import Path

import yaml

ITEM_ID_BASE = 0x54500000
LOCATION_ID_BASE = 0x55000000

ROOT = Path(__file__).resolve().parent.parent
DATA = Path(__file__).resolve().parent / "data"

# Locations the apworld never turns into checks (always vanilla, see pools.ALWAYS_VANILLA_NAMES
# and the "Warp Portal" category), so the tracker does not need them.
NEVER_CHECKS = ("Twilit Insect", "Twilit Bloat", "Defeat Ganondorf")


def read_apworld(path: Path) -> tuple[list, list]:
    def load(raw: bytes):
        return yaml.safe_load(io.TextIOWrapper(io.BytesIO(raw), encoding="utf-8"))

    if path.is_dir():
        base = path / "data"
        return (yaml.safe_load((base / "items.yaml").read_text("utf-8")),
                yaml.safe_load((base / "locations.yaml").read_text("utf-8")))
    with zipfile.ZipFile(path) as z:
        def find(suffix: str) -> bytes:
            for n in z.namelist():
                if n.endswith("/data/" + suffix):
                    return z.read(n)
            raise FileNotFoundError(suffix)
        return load(find("items.yaml")), load(find("locations.yaml"))


def categories(loc: dict) -> set[str]:
    cats = {c for c in (loc.get("Categories") or []) if c}
    if isinstance(loc.get("Metadata"), dict):
        cats.update(loc["Metadata"].keys())
    return cats


def is_check(loc: dict) -> bool:
    cats = categories(loc)
    if cats & {"Non-Item Location", "Placeholder", "Warp Portal"}:
        return False
    return not any(n in loc["Name"] for n in NEVER_CHECKS)


def lua_str(s: str) -> str:
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def main() -> int:
    if len(sys.argv) != 2:
        print(__doc__)
        return 2
    items, locations = read_apworld(Path(sys.argv[1]))
    item_codes = {k: v for k, v in json.loads((DATA / "item_codes.json").read_text("utf-8")).items()
                  if not k.startswith("_")}
    loc_paths = json.loads((DATA / "location_paths.json").read_text("utf-8"))

    # ---- items
    item_ids = {it["Name"]: int(it["Id"]) for it in items}
    lines = [
        "-- GENERATED by tools/gen_mappings.py from the Dusklight apworld. Do not edit by hand:",
        "-- change tools/data/item_codes.json and rerun the script.",
        f"ITEM_BASE = 0x{ITEM_ID_BASE:08X}",
        "",
        "ITEM_MAPPING = {",
    ]
    for name, (code, typ) in item_codes.items():
        if name not in item_ids:
            print(f"warning: item not in apworld: {name}")
            continue
        lines.append(f"\t[ITEM_BASE + 0x{item_ids[name]:02X}] = {{{lua_str(code)}, {lua_str(typ)}}}, -- {name}")
    lines.append("}")
    old = (ROOT / "scripts/item_mapping.lua").read_text("utf-8")
    tail = old[old.index("BUGS_ARRAY"):] if "BUGS_ARRAY" in old else ""
    (ROOT / "scripts/item_mapping.lua").write_text("\n".join(lines) + "\n\n" + tail, "utf-8")
    unmapped_items = [n for n, i in item_ids.items() if i <= 0xFF and n not in item_codes]

    # ---- locations
    lines = [
        "-- GENERATED by tools/gen_mappings.py from the Dusklight apworld. Do not edit by hand:",
        "-- change tools/data/location_paths.json and rerun the script.",
        "-- id = LOCATION_BASE + (crc32(name) & 0xFFFFFF), as in the apworld.",
        f"LOCATION_BASE = 0x{LOCATION_ID_BASE:08X}",
        "",
        "LOCATION_MAPPING = {",
    ]
    ids: dict[int, str] = {}
    missing = []
    known = {loc["Name"] for loc in locations}
    for loc in locations:
        name = loc["Name"]
        if not is_check(loc):
            continue
        paths = loc_paths.get(name)
        if not paths:
            missing.append(name)
            continue
        crc = zlib.crc32(name.encode("utf-8")) & 0xFFFFFF
        assert crc not in ids, f"id collision: {name} / {ids[crc]}"
        ids[crc] = name
        lua_paths = ", ".join(lua_str(p) for p in paths)
        lines.append(f"\t[LOCATION_BASE + 0x{crc:06X}] = {{{lua_paths}}}, -- {name}")
    lines.append("}")
    lines.append("")
    # Name -> id, for code that needs to look a location up by its apworld name.
    lines.append("LOCATION_NAME_TO_ID = {")
    for crc, name in ids.items():
        lines.append(f"\t[{lua_str(name)}] = LOCATION_BASE + 0x{crc:06X},")
    lines.append("}")
    (ROOT / "scripts/location_mapping.lua").write_text("\n".join(lines) + "\n", "utf-8")

    stale = sorted(set(loc_paths) - known)
    print(f"items: {len(item_codes)} mapped, {len(unmapped_items)} apworld items ignored")
    print(f"locations: {len(ids)} mapped")
    if missing:
        print(f"locations in the apworld with no tracker section ({len(missing)}):")
        for n in missing:
            print("  ", n)
    if stale:
        print(f"tracker locations no longer in the apworld ({len(stale)}):")
        for n in stale:
            print("  ", n)
    return 0


if __name__ == "__main__":
    sys.exit(main())
